// Strict union type generated automatically from the list above.
// Example result: "USD" | "EUR" | "GBP" | "GHS" | ... etc.
export type TCurrencyCode = (typeof currencyList)[number]['code'];

// Array of just the codes — useful for Mongoose `enum` validation.
export const currencyCodes = currencyList.map((c) => c.code) as TCurrencyCode[];

// Shape used by the frontend Select/Combobox `currencyOptions.map(...)`
export const currencyOptions = currencyList.map((item) => ({
  code: item.code,
  name: item.name,
  symbol: item.symbol,
}));

// Helper to look up a currency's full details from just its code.
// Useful anywhere you need to display the symbol (e.g. pricing screens).
export function getCurrencyByCode(code: string) {
  return currencyList.find((c) => c.code === code);
}
